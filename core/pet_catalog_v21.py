def wizard_pages(species,breed_name=''):
    pages=list(PAGES.get(species,()))
    if breed_name in LONG_HAIR:
        pages.insert(next(i for i,p in enumerate(pages) if p[0]=='feed'),('groom','梳理用品',True))
